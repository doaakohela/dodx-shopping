export function matchesPriceTier(numericPrice: number, tierId: PriceTierId): boolean {
  if (tierId === 'all') return true;
  const tier = PRICE_TIERS.find((t) => t.id === tierId);
  if (!tier) return true;
  if (tier.max === null) {
    return numericPrice > tier.min;
  }
  return numericPrice >= tier.min && numericPrice <= tier.max;
}

export function getPriceTierForNumber(numericPrice: number): PriceTierId {
  for (const tier of PRICE_TIERS) {
    if (tier.max === null) {
      if (numericPrice > tier.min) return tier.id;
    } else if (numericPrice >= tier.min && numericPrice <= tier.max) {
      return tier.id;
    }
  }
  return '1-30';
}

export function getStoreBranch(storeId: string): StoreBranch | undefined {
  for (const g of STORE_GROUPS) {
    const branch = g.branches.find((b) => b.id === storeId);
    if (branch) return branch;
  }
  return undefined;
}

export function getStoreGroup(groupOrStoreId: string): StoreGroup | undefined {
  const normalized = groupOrStoreId.trim().toLowerCase();
  return STORE_GROUPS.find(
    (g) =>
      g.id === normalized ||
      g.branches.some((b) => b.id === normalized || b.domain.toLowerCase() === normalized)
  );
}

