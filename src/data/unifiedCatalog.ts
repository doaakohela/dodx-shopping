export function getStoreProductCurrencyInfo(storeId: string): {
  symbol: string;
  currencyAr: string;
} {
  const branch = getStoreBranch(storeId);
  if (branch) {
    return { symbol: branch.currencySymbol, currencyAr: branch.currencyAr };
  }
  return { symbol: '$', currencyAr: 'دولار' };
}

export function getProductsByStore(storeOrGroupId: string): CatalogProduct[] {
  const group = getStoreGroup(storeOrGroupId);
  if (group && group.id === storeOrGroupId.toLowerCase()) {
    const branchIds = new Set(group.branches.map((b) => b.id));
    return CATALOG_PRODUCTS.filter((p) => branchIds.has(p.storeId));
  }
  return CATALOG_PRODUCTS.filter((p) => p.storeId === storeOrGroupId);
}
