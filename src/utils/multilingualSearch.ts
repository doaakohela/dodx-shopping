const NORMALIZED_GROUPS: string[][] = SYNONYM_GROUPS.map((group) =>
  group.map((term) => normalizeSearchText(term))
);

/**
 * Expands a raw user search query into all matching multilingual query variants.
 */
export function expandMultilingualQuery(rawQuery: string): string[] {
  const norm = normalizeSearchText(rawQuery);
  if (!norm) return [];

  const tokens = extractSearchTokens(norm);
  const expanded = new Set<string>([norm, ...tokens]);

  for (const group of NORMALIZED_GROUPS) {
    const groupMatched = group.some((term) => {
      if (norm === term) return true;
      if (norm.length >= 4 && term.length >= 3 && norm.includes(term)) return true;
      return tokens.some(
        (tok) =>
          tok === term ||
          (tok.length >= 3 && term.length >= 3 && (tok.includes(term) || term.includes(tok)))
      );
    });

    if (groupMatched) {
      for (const term of group) {
        expanded.add(term);
      }
    }
  }

  return Array.from(expanded);
}

/**
 * Returns a relevance score (>0 if matched, 0 if not) so exact/direct matches rank above broad synonyms.
 */
export function scoreMultilingualMatch(
  searchableText: string,
  rawQuery: string
): number {
  const normQuery = normalizeSearchText(rawQuery);
  if (!normQuery) return 1;

  const normHay = normalizeSearchText(searchableText);
  if (!normHay) return 0;

  let score = 0;

  if (normHay.includes(normQuery)) {
    score += 100;
  }

  const queryTokens = extractSearchTokens(normQuery);
  for (const tok of queryTokens) {
    if (tok.length >= 2 && normHay.includes(tok)) {
      score += 40;
    }
  }

  const expandedTerms = expandMultilingualQuery(rawQuery);
  for (const term of expandedTerms) {
    if (term.length >= 2 && normHay.includes(term)) {
      score += term === normQuery ? 50 : 12;
    }
  }

  return score;
}

/**
 * Returns true if the searchable text matches the user's query either directly
 * or through multilingual synonym expansion.
 */
export function matchesMultilingualQuery(
  searchableText: string,
  rawQuery: string
): boolean {
  return scoreMultilingualMatch(searchableText, rawQuery) > 0;
}
