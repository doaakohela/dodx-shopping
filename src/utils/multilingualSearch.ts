function extractSearchTokens(normText: string): string[] {
  const rawTokens = normText.split(/\s+/).filter(Boolean);
  const tokens = new Set<string>();

  for (const tok of rawTokens) {
    if (STOPWORDS.has(tok)) continue;
    tokens.add(tok);
    // Strip Arabic definite prefix "ال" on 4+ letter words (e.g., الهواتف -> هواتف)
    if (tok.startsWith('ال') && tok.length >= 4) {
      tokens.add(tok.slice(2));
    }
    // Strip common Arabic attached prepositions ب / ل / ك before الـ (e.g. بالهواتف / للهواتف)
    if (/^[بلك]ال/.test(tok) && tok.length >= 5) {
      tokens.add(tok.slice(3));
    }
  }

  return Array.from(tokens);
}

