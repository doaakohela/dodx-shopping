export function normalizeSearchText(input: string): string {
  return input
    .toLowerCase()
    .normalize('NFKD')
    .replace(/[\u064B-\u065F\u0670\u0640]/g, '') // Arabic diacritics & tatweel
    .replace(/[أإآٱ]/g, 'ا')
    .replace(/ة/g, 'ه')
    .replace(/ى/g, 'ي')
    .replace(/ؤ/g, 'و')
    .replace(/ئ/g, 'ي')
    .replace(/[،؛؟.,!:/\\()[\]{}"'`~@#$%^&*_+=<>|-]+/g, ' ')
    .replace(/\s+/g, ' ')
    .trim();
}

